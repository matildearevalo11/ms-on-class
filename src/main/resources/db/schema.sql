CREATE TABLE IF NOT EXISTS bootcamps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    launch_date DATE NOT NULL,
    duration_days INTEGER NOT NULL CHECK (duration_days > 0),
    CONSTRAINT ck_bootcamp_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_bootcamp_description CHECK (CHAR_LENGTH(TRIM(description)) > 0)
);

CREATE TABLE IF NOT EXISTS bootcamp_capacities (
    bootcamp_id BIGINT NOT NULL REFERENCES bootcamps(id) ON DELETE CASCADE,
    capacity_id BIGINT NOT NULL,
    PRIMARY KEY (bootcamp_id, capacity_id)
);

CREATE TABLE IF NOT EXISTS bootcamp_enrollments (
    person_id BIGINT NOT NULL,
    bootcamp_id BIGINT NOT NULL REFERENCES bootcamps(id) ON DELETE CASCADE,
    PRIMARY KEY (person_id, bootcamp_id)
);

CREATE TABLE IF NOT EXISTS report_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bootcamp_id BIGINT NOT NULL UNIQUE,
    payload TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_report_outbox_pending ON report_outbox (id) WHERE delivered_at IS NULL;

CREATE TABLE IF NOT EXISTS report_person_count_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bootcamp_id BIGINT NOT NULL REFERENCES bootcamps(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMP
);
